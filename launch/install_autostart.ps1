<#
.SYNOPSIS
    注册/更新「阿尔比恩」在仓库外的两个入口（幂等，可重复跑）。

.DESCRIPTION
    1) 计划任务 AlbionBrainWatch：wscript launch\hidden.vbs -> launch\brain_watch.ps1，每 2 分钟补一次脑。
       （壳没在跑就不管；脑在 WSL 里，只走幂等的 start.sh，不做 wsl --shutdown。）
    2) 启动文件夹里的 AlbionStatus.vbs：改成调仓库自带的 widget\AlbionStatus.vbs，
       解释器由它自己按 ALBION_PYTHONW -> PATH 上的 pythonw/pyw/py -> Python313 依次找，不再写死 pythonw。

    已经一致就跳过（[skip]）；不一致才改。先跑 -DryRun 看计划。

.PARAMETER DryRun
    只打印将要做什么，不碰系统（不建任务、不写文件）。

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File launch\install_autostart.ps1 -DryRun

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File launch\install_autostart.ps1
#>
param([switch]$DryRun)

$ErrorActionPreference = 'Stop'

$Root       = Split-Path -Parent $PSScriptRoot
$HiddenVbs  = Join-Path $Root 'launch\hidden.vbs'
$BrainWatch = Join-Path $Root 'launch\brain_watch.ps1'
$WidgetVbs  = Join-Path $Root 'widget\AlbionStatus.vbs'
$TaskName   = 'AlbionBrainWatch'
$TaskArgs   = '"' + $HiddenVbs + '" "powershell -NoProfile -ExecutionPolicy Bypass -File ' + $BrainWatch + '"'

$StartupDir = [Environment]::GetFolderPath('Startup')
$StartupVbs = Join-Path $StartupDir 'AlbionStatus.vbs'

# 生成的启动项保持纯 ASCII：WSH 在无 BOM 时按 ANSI 读 .vbs，中文注释会变乱码。
$StartupTemplate = @'
' Generated by launch\install_autostart.ps1 (idempotent: re-running rewrites the same body).
' Starts the Albion status widget on logon through the repo copy at
' widget\AlbionStatus.vbs; that script finds pythonw itself
' (ALBION_PYTHONW -> PATH pythonw/pyw/py -> Python313), so no interpreter path is pinned here.
Option Explicit
Dim sh
Set sh = CreateObject("WScript.Shell")
sh.Run "wscript.exe ""__WIDGET__""", 0, False
'@
$StartupBody = $StartupTemplate.Replace('__WIDGET__', $WidgetVbs)

function Write-Plan([string]$Text) { Write-Host ('[plan] ' + $Text) -ForegroundColor Cyan }
function Write-Skip([string]$Text) { Write-Host ('[skip] ' + $Text) }
function Write-Done([string]$Text) { Write-Host ('[ok]   ' + $Text) -ForegroundColor Green }

foreach ($p in @($HiddenVbs, $BrainWatch, $WidgetVbs)) {
    if (-not (Test-Path -LiteralPath $p)) { throw ('缺少文件：' + $p + '（脚本要在仓库的 launch\ 目录里跑）') }
}

if ($DryRun) { Write-Host '=== DryRun：只打印，不改系统 ===' -ForegroundColor Yellow }

# ---- 1) 计划任务 ------------------------------------------------------------
$existing = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
$sameTask = $false
if ($existing) {
    $act = $existing.Actions | Select-Object -First 1
    $sameTask = ($act.Execute -eq 'wscript.exe') -and ($act.Arguments -eq $TaskArgs)
}

if ($sameTask) {
    Write-Skip ('计划任务 ' + $TaskName + ' 已是最新')
} else {
    $verb = if ($existing) { '更新' } else { '新建' }
    Write-Plan ($verb + '计划任务 ' + $TaskName)
    Write-Plan '  Execute   : wscript.exe'
    Write-Plan ('  Arguments : ' + $TaskArgs)
    Write-Plan ('  Trigger   : 起始 ' + (Get-Date).AddMinutes(1).ToString('yyyy-MM-dd HH:mm:ss') + '，每 2 分钟重复，持续 3650 天')
    Write-Plan ('  Principal : ' + $env:USERNAME + ' / Interactive / Limited')
    if (-not $DryRun) {
        $action  = New-ScheduledTaskAction -Execute 'wscript.exe' -Argument $TaskArgs
        $trigger = New-ScheduledTaskTrigger -Once -At (Get-Date).AddMinutes(1) `
            -RepetitionInterval (New-TimeSpan -Minutes 2) -RepetitionDuration (New-TimeSpan -Days 3650)
        $settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
            -StartWhenAvailable -ExecutionTimeLimit ([TimeSpan]::Zero)
        Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Settings $settings `
            -User $env:USERNAME -Description '阿尔比恩脑看门狗：壳在跑而 WSL 脑不通时补一次 start.sh（每 2 分钟）' -Force | Out-Null
        Write-Done ('计划任务已写入：' + $TaskName)
    }
}

# ---- 2) 启动文件夹 ----------------------------------------------------------
$currentBody = if (Test-Path -LiteralPath $StartupVbs) { (Get-Content -LiteralPath $StartupVbs -Raw) } else { $null }
$sameStartup = $currentBody -and ($currentBody.Replace("`r`n", "`n").Trim() -eq $StartupBody.Replace("`r`n", "`n").Trim())

if ($sameStartup) {
    Write-Skip ('启动项已是最新：' + $StartupVbs)
} else {
    $verb = if ($currentBody) { '改写' } else { '新建' }
    Write-Plan ($verb + '启动项 ' + $StartupVbs)
    Write-Plan ('  内容 -> 调仓库里的 ' + $WidgetVbs + '（pythonw 由它自己找）')
    if (-not $DryRun) {
        $body = ($StartupBody -replace "`r`n", "`n") -replace "`n", "`r`n"
        [System.IO.File]::WriteAllText($StartupVbs, $body, (New-Object System.Text.ASCIIEncoding))
        Write-Done ('启动项已写入：' + $StartupVbs)
    }
}

if ($DryRun) {
    Write-Host '=== DryRun 结束：什么也没改 ===' -ForegroundColor Yellow
} else {
    Write-Host ''
    Write-Host '核对：'
    Write-Host ('  Get-ScheduledTask -TaskName ' + $TaskName + ' | ForEach-Object { $_.Actions }')
    Write-Host ('  Get-Content "' + $StartupVbs + '"')
}
